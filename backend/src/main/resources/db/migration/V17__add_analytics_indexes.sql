-- Индексы под аналитику во времени.
--
-- idx_items_finished_at из V11 построен по одной колонке и годится для «что дочитано за период»
-- по всей базе. Аналитика же почти всегда спрашивает про одного человека, и составной индекс
-- закрывает и отбор по владельцу, и группировку по дате завершения одним проходом.
CREATE INDEX idx_items_created_by_finished ON library_items (created_by, finished_at);

-- Разбивка по языку группирует по нормализованному значению, поэтому и индекс — по выражению:
-- по голой колонке он для такой группировки бесполезен.
CREATE INDEX idx_items_language ON library_items (LOWER(language)) WHERE language IS NOT NULL;

