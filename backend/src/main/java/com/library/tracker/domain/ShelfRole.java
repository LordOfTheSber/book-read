package com.library.tracker.domain;

/**
 * Роль внутри полки. Отдельно от {@link Role}: глобальная роль отвечает на вопрос «что человеку
 * можно в сервисе», а эта — «что ему можно на этой полке». Участник книжного клуба не становится
 * администратором сервиса, а администратор не становится участником каждой полки.
 */
public enum ShelfRole {

    /** Видит состав полки. */
    VIEWER,
    /** Добавляет свои произведения и снимает их же. */
    CONTRIBUTOR,
    /** Правит состав целиком и ведёт список участников. */
    CURATOR
}
